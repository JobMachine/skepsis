// Copies Logos's course (units), sources and engine from the Logos repo into src/logos/vendor/,
// so the private iOS build (EAS never builds this; the owner's own Mac does) can bundle them.
// Logos's own repo stays the one source of truth: edit there, then run `npm run logos:sync`.
// New episodes arrive by re-running this script: every unit file (u01.js, u02.js, ...) is picked up
// and listed in the generated index, so no app code changes.
// Default source: ../../philosophy (the sibling checkout). Override with LOGOS_DIR=/path/to/logos.
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(process.env.LOGOS_DIR || path.join(here, "../../../philosophy"));
const out = path.join(here, "../src/logos/vendor");
const unitsDir = path.join(src, "app/src/units");
if (!existsSync(unitsDir)) throw new Error(`Logos not found at ${src} (set LOGOS_DIR)`);

const units = readdirSync(unitsDir)
  .filter((f) => /^u\d+\.js$/.test(f))
  .sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));

rmSync(out, { recursive: true, force: true });
mkdirSync(path.join(out, "units"), { recursive: true });
copyFileSync(path.join(src, "app/src/engine.js"), path.join(out, "engine.js"));
copyFileSync(path.join(src, "app/src/sources.json"), path.join(out, "sources.json"));
for (const f of units) copyFileSync(path.join(unitsDir, f), path.join(out, "units", f));
writeFileSync(
  path.join(out, "index.js"),
  `// GENERATED by scripts/sync-logos.mjs from the Logos repo. Do not edit; edit Logos and re-sync.\n` +
    `/* eslint-disable */\n` +
    `module.exports = {\n  Engine: require("./engine.js").Engine,\n  sources: require("./sources.json"),\n  units: [\n${units.map((f) => `    require("./units/${f}"),`).join("\n")}\n  ],\n};\n`,
);
console.log(`Synced Logos: engine + sources + ${units.length} unit file(s) from ${src}`);
