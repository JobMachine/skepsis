// Copies Komorebi's course (units) and engine from the Komorebi repo into src/komorebi/vendor/,
// so the iOS build (EAS uploads only this repo) can bundle them.
// Komorebi's own repo stays the one source of truth: edit there, then run `npm run komorebi:sync`.
// Default source: ../../japanese (the sibling checkout). Override with KOMOREBI_DIR=/path/to/komorebi.
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(process.env.KOMOREBI_DIR || path.join(here, "../../../japanese"));
const out = path.join(here, "../src/komorebi/vendor");
const unitsDir = path.join(src, "app/src/units");
if (!existsSync(unitsDir)) throw new Error(`Komorebi not found at ${src} (set KOMOREBI_DIR)`);

const units = readdirSync(unitsDir)
  .filter((f) => /^u\d+\.js$/.test(f))
  .sort((a, b) => parseInt(a.slice(1)) - parseInt(b.slice(1)));

rmSync(out, { recursive: true, force: true });
mkdirSync(path.join(out, "units"), { recursive: true });
copyFileSync(path.join(src, "app/src/engine.js"), path.join(out, "engine.js"));
for (const f of units) copyFileSync(path.join(unitsDir, f), path.join(out, "units", f));
writeFileSync(
  path.join(out, "index.js"),
  `// GENERATED by scripts/sync-komorebi.mjs from the Komorebi repo. Do not edit; edit Komorebi and re-sync.\n` +
    `/* eslint-disable */\n` +
    `module.exports = {\n  Engine: require("./engine.js").Engine,\n  units: [\n${units.map((f) => `    require("./units/${f}"),`).join("\n")}\n  ],\n};\n`,
);
console.log(`Synced Komorebi: engine + ${units.length} units from ${src}`);
